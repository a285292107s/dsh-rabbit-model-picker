const path = require('node:path')
const os = require('node:os')
const { pathToFileURL } = require('node:url')
function lp () { for (const b of [path.join(os.homedir(),'AppData','Roaming','npm','node_modules','@playwright','cli'), path.join(__dirname,'..')]) { try { return require(require.resolve('playwright',{paths:[b]})) } catch {} } }
;(async () => {
  const p = lp(); const br = await p.chromium.launch()
  const pg = await br.newPage({ viewport: { width: 620, height: 1000 }, deviceScaleFactor: 2 })
  await pg.goto(pathToFileURL(path.join(__dirname,'..','shots','_drawer-preview.html')).href)
  await pg.waitForTimeout(300)
  const panel = pg.locator('.dmc-drawer')
  await pg.evaluate(() => document.body.setAttribute('data-ds-dark-theme',''))
  await pg.waitForTimeout(200)
  await panel.screenshot({ path: path.join(__dirname,'..','shots','model-config-37-drawer-dark.png') })
  await pg.evaluate(() => document.body.removeAttribute('data-ds-dark-theme'))
  await pg.waitForTimeout(200)
  await panel.screenshot({ path: path.join(__dirname,'..','shots','model-config-38-drawer-light.png') })
  await br.close()
  console.log('drawer theme shots written')
})()
